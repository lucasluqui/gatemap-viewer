#!/usr/bin/env python3
"""Regenerate lib/moment-timezone-data.js from moment-timezone's packed IANA data.

    python scripts/update-tz-data.py            # uses the version below
    python scripts/update-tz-data.py 0.6.7      # use a different moment-timezone release

Upon a version change also update lib/moment-timezone.min.js to the same release:
    https://cdnjs.cloudflare.com/ajax/libs/moment-timezone/<version>/moment-timezone.min.js
"""
import json
import sys
import urllib.request
from pathlib import Path

VERSION = '0.6.6'
ZONES = ('America/Chicago', 'America/Los_Angeles')
OUT = Path(__file__).resolve().parent.parent / 'lib' / 'moment-timezone-data.js'


def main():
    version = sys.argv[1] if len(sys.argv) > 1 else VERSION
    url = f'https://cdn.jsdelivr.net/npm/moment-timezone@{version}/data/packed/latest.json'
    with urllib.request.urlopen(url) as resp:
        data = json.load(resp)

    zones = [z for z in data['zones'] if z.split('|', 1)[0] in ZONES]
    found = {z.split('|', 1)[0] for z in zones}
    missing = set(ZONES) - found
    if missing:
        sys.exit(f'Zones not found in {url}: {", ".join(sorted(missing))}')

    packed = {'version': data['version'], 'zones': zones, 'links': [], 'countries': []}
    OUT.write_text(
        f'// IANA tz data {data["version"]} (moment-timezone {version}), '
        f'filtered to {" and ".join(ZONES)}.\n'
        f'// Generated by scripts/update-tz-data.py; do not edit by hand.\n'
        f'moment.tz.load({json.dumps(packed, separators=(",", ":"))});\n',
        encoding='utf-8',
        newline='\n',
    )
    print(f'Wrote {OUT} (tz data {data["version"]}, {len(zones)} zones)')


if __name__ == '__main__':
    main()
